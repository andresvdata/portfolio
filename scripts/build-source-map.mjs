#!/usr/bin/env node
/**
 * Builds docs/SOURCE_MAP.md from the `source` fields in src/content.
 * Run it after you add or change content:   npm run docs:sources
 *
 * Every claim on the site has a source code, so a reader (or you) can trace it back to the resume,
 * LinkedIn export, old portfolio, a public repository or a paper abstract.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p), 'utf8');
const yaml = (p) => parse(read(p));
const esc = (v) => String(v ?? '').replace(/\s+/g, ' ').replace(/\|/g, '\\|').trim();

function frontmatter(text) {
  const m = /^---\n([\s\S]*?)\n---/.exec(text);
  return m ? parse(m[1]) : {};
}

const out = [];
const table = (heading, head, rows, note) => {
  out.push(`## ${heading}`, '');
  if (note) out.push(note, '');
  out.push(`| ${head.join(' | ')} |`, `| ${head.map(() => '---').join(' | ')} |`);
  rows.forEach((r) => out.push(`| ${r.map(esc).join(' | ')} |`));
  out.push('');
};

out.push(
  '# Source map',
  '',
  'Generated by `npm run docs:sources`. Do not edit by hand: change the `source` field next to the claim instead.',
  '',
  '## Source codes',
  '',
  '| Code | Meaning |',
  '| --- | --- |',
  '| RES | `Master.docx`, the master resume (main factual source) |',
  '| LI | `Profile.pdf`, the LinkedIn export |',
  '| OLD | The previous portfolio, used as a source of facts only (this site never links to it) |',
  '| GH | A public repository under `github.com/andresvdata` (README, notebooks, files) |',
  '| ABS | The published abstract of a paper (DOI) |',
  '| POSTER | The SmartEnerx team datafolio poster |',
  '| ASK | Confirmed by Andres in a review session (date given next to the code) |',
  '',
  'When sources disagree, the site uses the more conservative value and the conflict is listed in `docs/QUESTIONS_FOR_ANDRES.md`.',
  '',
);

table('Home page highlights', ['Value', 'Label', 'Source'], yaml('src/content/data/highlights.yaml').map((h) => [h.value, h.label, h.source]));
table('Career story', ['Period', 'Chapter', 'Source'], yaml('src/content/data/story.yaml').map((s) => [s.period, s.title, s.source]));

const exp = readdirSync(join(root, 'src/content/experience')).filter((f) => f.endsWith('.yaml'));
const expRows = [];
for (const f of exp) {
  const e = yaml(`src/content/experience/${f}`);
  expRows.push([e.org, 'Dates and titles', e.sourceNote]);
  expRows.push([e.org, e.summary, e.summarySource]);
}
table('Experience', ['Employer', 'Claim', 'Source'], expRows);

const projects = readdirSync(join(root, 'src/content/projects')).filter((f) => f.endsWith('.md'));
const projRows = [];
for (const f of projects) {
  const d = frontmatter(read(`src/content/projects/${f}`));
  if (d.draft) continue;
  if (d.metric) projRows.push([d.title, `Headline: ${d.metric.value} ${d.metric.label}`, d.metric.source]);
  (d.result?.points ?? []).forEach((p) => projRows.push([d.title, p.text, p.source]));
  (d.sources ?? []).forEach((s) => projRows.push([d.title, 'Page overall', s]));
}
table('Case studies', ['Case study', 'Claim', 'Source'], projRows);

table(
  'Skills matrix',
  ['Skill', 'Source'],
  yaml('src/content/data/skills.yaml').map((s) => [s.label, s.source]),
  'A dot appears in the matrix only where the source documents the skill in that role.',
);
table('Map pins', ['Place', 'Source'], yaml('src/content/data/pins.yaml').map((p) => [p.label, p.source]));
table('Publications, education and accomplishments', ['Item', 'Source'], yaml('src/content/data/credentials.yaml').map((c) => [c.title, c.source]));
table('More work (compact rows)', ['Project', 'Source'], yaml('src/content/data/more.yaml').map((m) => [m.title, m.source]));

writeFileSync(join(root, 'docs/SOURCE_MAP.md'), out.join('\n'));
console.log(`Wrote docs/SOURCE_MAP.md (${out.length} lines).`);
